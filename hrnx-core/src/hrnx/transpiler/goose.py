from __future__ import annotations

from typing import TYPE_CHECKING, List
from hrnx.models.schema import Directive, HarnessNode, Severity, Skill, ToolSpec
from hrnx.transpiler.base import BaseAgentTranspiler, CompatibilityDiagnostic, GeneratedArtifact

if TYPE_CHECKING:
    from hrnx.workspace import Workspace


class GooseTranspiler(BaseAgentTranspiler):
    target_id = "goose"
    target_name = "Goose (Block)"
    target_file = ".goosehints"
    supported_primitives = {"directives", "skills", "tools"}

    def compile(self, workspace: Workspace) -> List[GeneratedArtifact]:
        artifacts: List[GeneratedArtifact] = []
        nodes = workspace.graph.all_nodes()
        directives = [n for n in nodes if isinstance(n, Directive)]
        skills = [n for n in nodes if isinstance(n, Skill)]
        tools = [n for n in nodes if isinstance(n, ToolSpec)]

        # 1. Main .goosehints
        hints_lines = [
            "# Goose Execution Hints & Policies",
            "# AUTO-GENERATED BY HRNX - DO NOT EDIT MANUALLY",
            "",
            "## Mandatory Invariants",
            "",
        ]

        for d in directives:
            sev = d.severity.value if hasattr(d.severity, "value") else str(d.severity)
            prefix = "[FATAL] " if sev == Severity.FATAL_INVARIANT.value else ""
            hints_lines.append(f"### {prefix}{d.title} (`{d.id}`)")
            if d.body:
                hints_lines.append(d.body.strip())
            hints_lines.append("")

        if skills:
            hints_lines.extend([
                "## Execution Workflows",
                "",
            ])
            for s in skills:
                hints_lines.append(f"### {s.title} (`{s.id}`)")
                if s.body:
                    hints_lines.append(s.body.strip())
                hints_lines.append("")

        artifacts.append(
            GeneratedArtifact(
                target=self.target_id,
                path=".goosehints",
                content="\n".join(hints_lines),
                description="Actionable runtime hints for Goose agent",
            )
        )

        # 2. .goose/config.yaml for extensions/tools
        config_lines = [
            "# Goose Tool Configuration",
            "# AUTO-GENERATED BY HRNX",
            "extensions:",
        ]
        if tools:
            for t in tools:
                tool_name = t.id.replace("tool.", "").replace(".", "_")
                config_lines.extend([
                    f"  {tool_name}:",
                    f"    name: \"{t.title}\"",
                    f"    type: \"command\"",
                    f"    cmd: \"{t.body.strip() if t.body else 'echo'}\"",
                ])
        else:
            config_lines.append("  {}")

        artifacts.append(
            GeneratedArtifact(
                target=self.target_id,
                path=".goose/config.yaml",
                content="\n".join(config_lines),
                description="Goose extension configuration",
            )
        )

        return artifacts

    def preview_node(self, node: HarnessNode, workspace: Workspace) -> GeneratedArtifact:
        sev = getattr(node, "severity", None)
        sev_tag = f"[{sev.value.upper()}] " if sev else ""
        lines = [
            f"### {sev_tag}{node.title} (`{node.id}`)",
            "",
            getattr(node, "body", "").strip(),
        ]
        return GeneratedArtifact(
            target=self.target_id,
            path=".goosehints",
            content="\n".join(lines),
            description="Goose hint preview",
        )

    def validate_compatibility(self, node: HarnessNode) -> List[CompatibilityDiagnostic]:
        diagnostics: List[CompatibilityDiagnostic] = []
        if isinstance(node, Skill):
            diagnostics.append(
                CompatibilityDiagnostic(
                    node_id=node.id,
                    target=self.target_id,
                    message="Goose is single-session and lacks multi-agent routing; skill compiled as flat hints.",
                    severity="warning",
                    feature="subagents",
                    lossy=True,
                )
            )
        elif isinstance(node, ToolSpec):
            diagnostics.append(
                CompatibilityDiagnostic(
                    node_id=node.id,
                    target=self.target_id,
                    message="Tool spec compiled into .goose/config.yaml extension definition.",
                    severity="info",
                    feature="tools",
                    lossy=False,
                )
            )
        return diagnostics
