from __future__ import annotations

from typing import TYPE_CHECKING, List
from hrnx.models.schema import Directive, HarnessNode, Skill
from hrnx.transpiler.base import BaseAgentTranspiler, CompatibilityDiagnostic, GeneratedArtifact

if TYPE_CHECKING:
    from hrnx.workspace import Workspace


class CopilotTranspiler(BaseAgentTranspiler):
    target_id = "copilot"
    target_name = "GitHub Copilot"
    target_file = ".github/copilot-instructions.md"
    supported_primitives = {"directives", "skills"}

    def compile(self, workspace: Workspace) -> List[GeneratedArtifact]:
        nodes = workspace.graph.all_nodes()
        directives = [n for n in nodes if isinstance(n, Directive)]
        skills = [n for n in nodes if isinstance(n, Skill)]

        lines = [
            "# GitHub Copilot Coding Instructions",
            "<!-- AUTO-GENERATED BY HRNX - DO NOT EDIT MANUALLY -->",
            "",
            "## Architectural Invariants & Rules",
            "",
        ]
        for d in directives:
            sev = d.severity.value if hasattr(d.severity, "value") else str(d.severity)
            lines.append(f"- **[{sev.upper()}] {d.title} (`{d.id}`)**")
            if d.body:
                # Dense indentation for copilot prompt economy
                for bl in d.body.strip().splitlines():
                    lines.append(f"  > {bl}")
            lines.append("")

        lines.extend([
            "## Standard Workflows",
            "",
        ])
        for s in skills:
            lines.append(f"- **{s.title} (`{s.id}`)**")
            if s.body:
                for bl in s.body.strip().splitlines():
                    lines.append(f"  > {bl}")
            lines.append("")

        return [
            GeneratedArtifact(
                target=self.target_id,
                path=".github/copilot-instructions.md",
                content="\n".join(lines),
                description="Instructions checklist for GitHub Copilot",
            )
        ]

    def preview_node(self, node: HarnessNode, workspace: Workspace) -> GeneratedArtifact:
        sev = getattr(node, "severity", None)
        sev_tag = f"[{sev.value.upper()}] " if sev else ""
        lines = [
            f"- **{sev_tag}{node.title} (`{node.id}`)**",
        ]
        body = getattr(node, "body", "")
        if body:
            for bl in body.strip().splitlines():
                lines.append(f"  > {bl}")
        return GeneratedArtifact(
            target=self.target_id,
            path=".github/copilot-instructions.md",
            content="\n".join(lines),
        )

    def validate_compatibility(self, node: HarnessNode) -> List[CompatibilityDiagnostic]:
        diagnostics: List[CompatibilityDiagnostic] = []
        if getattr(node, "type", None) == "tool" or node.__class__.__name__ == "ToolSpec":
            diagnostics.append(
                CompatibilityDiagnostic(
                    node_id=node.id,
                    target=self.target_id,
                    message="GitHub Copilot does not support tool/MCP execution specs; omitted from prompt.",
                    severity="warning",
                    feature="tools",
                    lossy=True,
                )
            )
        elif getattr(node, "type", None) == "skill" or node.__class__.__name__ == "Skill":
            diagnostics.append(
                CompatibilityDiagnostic(
                    node_id=node.id,
                    target=self.target_id,
                    message="GitHub Copilot lacks autonomous subagents; workflow flattened to checklist bullets.",
                    severity="warning",
                    feature="subagents",
                    lossy=True,
                )
            )
        elif isinstance(node, Directive):
            diagnostics.append(
                CompatibilityDiagnostic(
                    node_id=node.id,
                    target=self.target_id,
                    message="Directive compiled to dense checklist format.",
                    severity="info",
                    feature="directives",
                    lossy=False,
                )
            )
        return diagnostics
