from __future__ import annotations

import json
from typing import TYPE_CHECKING, List
from hrnx.models.schema import Directive, HarnessNode, Severity, Skill, ToolSpec
from hrnx.transpiler.base import BaseAgentTranspiler, CompatibilityDiagnostic, GeneratedArtifact

if TYPE_CHECKING:
    from hrnx.workspace import Workspace


class ClineTranspiler(BaseAgentTranspiler):
    target_id = "cline"
    target_name = "Cline & Roo Code"
    target_file = ".clinerules"
    supported_primitives = {"directives", "skills", "tools", "roles", "evals"}

    def compile(self, workspace: Workspace) -> List[GeneratedArtifact]:
        artifacts: List[GeneratedArtifact] = []
        nodes = workspace.graph.all_nodes()
        directives = [n for n in nodes if isinstance(n, Directive)]
        skills = [n for n in nodes if isinstance(n, Skill)]
        tools = [n for n in nodes if isinstance(n, ToolSpec)]

        # 1. Main .clinerules
        clinerules_lines = [
            "# Cline & Roo Code Project Rules",
            "<!-- AUTO-GENERATED BY HRNX - DO NOT EDIT MANUALLY -->",
            "",
            "## Architectural Invariants & Fatal Policies",
            "",
        ]

        fatal_invariants = []
        advisory_rules = []

        for d in directives:
            sev = d.severity.value if hasattr(d.severity, "value") else str(d.severity)
            if sev == Severity.FATAL_INVARIANT.value:
                fatal_invariants.append(d)
            else:
                advisory_rules.append(d)

        for d in fatal_invariants:
            clinerules_lines.append(f"### [FATAL] {d.title} (`{d.id}`)")
            if d.body:
                clinerules_lines.append(d.body.strip())
            clinerules_lines.append("")

        if advisory_rules:
            clinerules_lines.extend([
                "## Advisory Guidelines & Policies",
                "",
            ])
            for d in advisory_rules:
                clinerules_lines.append(f"### {d.title} (`{d.id}`)")
                if d.body:
                    clinerules_lines.append(d.body.strip())
                clinerules_lines.append("")

        clinerules_lines.extend([
            "## Standard Workflows & Tasks",
            "",
        ])
        for s in skills:
            trigs = f" (Triggers: {', '.join(s.triggers)})" if s.triggers else ""
            clinerules_lines.append(f"### {s.title}{trigs}")
            if s.body:
                clinerules_lines.append(s.body.strip())
            clinerules_lines.append("")

        artifacts.append(
            GeneratedArtifact(
                target=self.target_id,
                path=".clinerules",
                content="\n".join(clinerules_lines),
                description="Core rules and invariants for Cline",
            )
        )

        # 2. Roo Code .roomodes custom modes configuration
        fatal_instructions = "\n".join(
            [f"- {d.title}: {d.body.strip()}" for d in fatal_invariants if d.body]
        )

        custom_modes = [
            {
                "slug": "harness-architect",
                "name": "Harness Architect",
                "roleDefinition": "You are the Harness Architect. You enforce foundational invariants, ADR compliance, and safe schema migrations.",
                "groups": ["read", ["edit", {"fileRegex": "\\.hrnx/.*"}], "browser", "command"],
                "customInstructions": f"Mandatory Fatal Invariants:\n{fatal_instructions}",
            },
            {
                "slug": "harness-security",
                "name": "Security & Safety Reviewer",
                "roleDefinition": "You are the Security Reviewer. You strictly guard credential isolation, authorization boundaries, and zero-downtime rules.",
                "groups": ["read", "command"],
                "customInstructions": f"Fatal Invariant Checklist:\n{fatal_instructions}",
            },
            {
                "slug": "harness-engineer",
                "name": "Harness Engineer",
                "roleDefinition": "You are the Implementation Engineer. Follow workflows and maintain compliance.",
                "groups": ["read", "edit", "browser", "command", "mcp"],
                "customInstructions": "Execute directives and conform to project skills and conventions.",
            },
        ]

        # Add skill-specific modes if any skills define discrete workflows
        for s in skills:
            if s.triggers:
                slug_name = s.id.replace("skill.", "").replace(".", "-")
                custom_modes.append({
                    "slug": f"workflow-{slug_name}",
                    "name": s.title,
                    "roleDefinition": f"Specialist agent dedicated to executing workflow: {s.title}",
                    "groups": ["read", "edit", "command", "mcp"],
                    "customInstructions": s.body.strip() if s.body else "",
                })

        roomodes_payload = {"customModes": custom_modes}
        artifacts.append(
            GeneratedArtifact(
                target=self.target_id,
                path=".roomodes",
                content=json.dumps(roomodes_payload, indent=2),
                description="Roo Code custom modes mapping personas, tools, and permissions",
            )
        )

        return artifacts

    def preview_node(self, node: HarnessNode, workspace: Workspace) -> GeneratedArtifact:
        if isinstance(node, Skill):
            lines = [
                f"# Roo Mode / Cline Task: {node.title} (`{node.id}`)",
                f"Triggers: {', '.join(node.triggers)}" if node.triggers else "",
                "",
                node.body.strip() if node.body else "",
            ]
            return GeneratedArtifact(
                target=self.target_id,
                path=".clinerules",
                content="\n".join(lines),
            )
        sev = getattr(node, "severity", None)
        sev_tag = f"[{sev.value.upper()}] " if sev else ""
        lines = [
            f"### {sev_tag}{node.title} (`{node.id}`)",
            "",
            getattr(node, "body", "").strip(),
        ]
        return GeneratedArtifact(
            target=self.target_id,
            path=".clinerules",
            content="\n".join(lines),
            description="Cline rule preview",
        )

    def validate_compatibility(self, node: HarnessNode) -> List[CompatibilityDiagnostic]:
        diagnostics: List[CompatibilityDiagnostic] = []
        if isinstance(node, Directive):
            sev = getattr(node, "severity", None)
            if sev == Severity.FATAL_INVARIANT:
                diagnostics.append(
                    CompatibilityDiagnostic(
                        node_id=node.id,
                        target=self.target_id,
                        message="Fatal invariant will be strictly enforced across all Roo Code custom modes (.roomodes).",
                        severity="info",
                        feature="fatal_invariant",
                        lossy=False,
                    )
                )
        elif isinstance(node, ToolSpec):
            diagnostics.append(
                CompatibilityDiagnostic(
                    node_id=node.id,
                    target=self.target_id,
                    message="Tool spec mapped to Roo Code MCP and shell command execution group.",
                    severity="info",
                    feature="tools",
                    lossy=False,
                )
            )
        elif isinstance(node, Skill):
            diagnostics.append(
                CompatibilityDiagnostic(
                    node_id=node.id,
                    target=self.target_id,
                    message="Skill mapped to dedicated Roo Code workflow mode and .clinerules task definition.",
                    severity="info",
                    feature="subagents",
                    lossy=False,
                )
            )
        return diagnostics
