from __future__ import annotations

import json
from typing import TYPE_CHECKING, List
from hrnx.models.schema import Directive, HarnessNode, Skill, ToolSpec
from hrnx.transpiler.base import BaseAgentTranspiler, CompatibilityDiagnostic, GeneratedArtifact

if TYPE_CHECKING:
    from hrnx.workspace import Workspace


class CodexTranspiler(BaseAgentTranspiler):
    target_id = "codex"
    target_name = "OpenAI Codex & Assistants"
    target_file = ".openai/instructions.md"
    supported_primitives = {"directives", "skills", "tools"}

    def compile(self, workspace: Workspace) -> List[GeneratedArtifact]:
        nodes = workspace.graph.all_nodes()
        directives = [n for n in nodes if isinstance(n, Directive)]
        skills = [n for n in nodes if isinstance(n, Skill)]
        tools = [n for n in nodes if isinstance(n, ToolSpec)]

        lines = [
            "# OpenAI Assistant System Instructions",
            "<!-- AUTO-GENERATED BY HRNX -->",
            "",
            "## Core Invariants & Security Rules",
            "",
        ]
        for d in directives:
            sev = d.severity.value if hasattr(d.severity, "value") else str(d.severity)
            lines.append(f"### Rule: {d.title} (`{d.id}`)")
            lines.append(f"Severity: {sev.upper()}")
            if d.body:
                lines.append(d.body.strip())
            lines.append("")

        lines.extend([
            "## Workflows & Capabilities",
            "",
        ])
        for s in skills:
            lines.append(f"### Workflow: {s.title} (`{s.id}`)")
            if s.body:
                lines.append(s.body.strip())
            lines.append("")

        artifacts = [
            GeneratedArtifact(
                target=self.target_id,
                path=".openai/instructions.md",
                content="\n".join(lines),
                description="Instructions prompt for OpenAI Codex",
            )
        ]

        # Tool specifications JSON
        tool_specs = []
        for t in tools:
            tool_specs.append({
                "type": "function",
                "function": {
                    "name": t.id.replace("tool.", "").replace(".", "_"),
                    "description": t.title,
                    "parameters": t.parameters or {"type": "object", "properties": {}},
                }
            })

        artifacts.append(
            GeneratedArtifact(
                target=self.target_id,
                path=".openai/tools.json",
                content=json.dumps(tool_specs, indent=2),
                description="OpenAI function declarations",
            )
        )

        return artifacts

    def preview_node(self, node: HarnessNode, workspace: Workspace) -> GeneratedArtifact:
        if isinstance(node, ToolSpec):
            spec = {
                "type": "function",
                "function": {
                    "name": node.id.replace("tool.", "").replace(".", "_"),
                    "description": node.title,
                    "parameters": node.parameters or {"type": "object", "properties": {}},
                }
            }
            return GeneratedArtifact(
                target=self.target_id,
                path=".openai/tools.json",
                content=json.dumps(spec, indent=2),
            )
        sev = getattr(node, "severity", "")
        sev_str = f" [Severity: {sev.value if hasattr(sev, 'value') else sev}]" if sev else ""
        lines = [
            f"### {node.title} (`{node.id}`){sev_str}",
            "",
            getattr(node, "body", "").strip(),
        ]
        return GeneratedArtifact(
            target=self.target_id,
            path=".openai/instructions.md",
            content="\n".join(lines),
        )

    def validate_compatibility(self, node: HarnessNode) -> List[CompatibilityDiagnostic]:
        diagnostics: List[CompatibilityDiagnostic] = []
        if isinstance(node, Skill):
            diagnostics.append(
                CompatibilityDiagnostic(
                    node_id=node.id,
                    target=self.target_id,
                    message="OpenAI Assistants synthesize subagents into sequential prompt instructions (no autonomous delegation).",
                    severity="warning",
                    feature="subagents",
                    lossy=True,
                )
            )
        elif isinstance(node, ToolSpec):
            diagnostics.append(
                CompatibilityDiagnostic(
                    node_id=node.id,
                    target=self.target_id,
                    message="Tool compiled to OpenAI Function Calling declaration in .openai/tools.json.",
                    severity="info",
                    feature="tools",
                    lossy=False,
                )
            )
        elif isinstance(node, Directive):
            diagnostics.append(
                CompatibilityDiagnostic(
                    node_id=node.id,
                    target=self.target_id,
                    message="Directive mapped to OpenAI system prompt rule block.",
                    severity="info",
                    feature="directives",
                    lossy=False,
                )
            )
        return diagnostics
