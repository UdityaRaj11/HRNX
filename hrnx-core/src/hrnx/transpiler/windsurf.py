from __future__ import annotations

from typing import TYPE_CHECKING, List
from hrnx.models.schema import Directive, HarnessNode, Severity, Skill, ToolSpec
from hrnx.transpiler.base import BaseAgentTranspiler, CompatibilityDiagnostic, GeneratedArtifact

if TYPE_CHECKING:
    from hrnx.workspace import Workspace


class WindsurfTranspiler(BaseAgentTranspiler):
    target_id = "windsurf"
    target_name = "Windsurf (Codeium)"
    target_file = ".windsurfrules"
    supported_primitives = {"directives", "skills", "tools"}

    def compile(self, workspace: Workspace) -> List[GeneratedArtifact]:
        nodes = workspace.graph.all_nodes()
        directives = [n for n in nodes if isinstance(n, Directive)]
        skills = [n for n in nodes if isinstance(n, Skill)]
        tools = [n for n in nodes if isinstance(n, ToolSpec)]

        lines = [
            "# Windsurf Cascade Rules & System Directives",
            "<!-- AUTO-GENERATED BY HRNX - DO NOT EDIT MANUALLY -->",
            "",
            "## Architectural Invariants (Enforced by Cascade)",
            "",
        ]

        fatal_directives = []
        advisory_directives = []

        for d in directives:
            sev = d.severity.value if hasattr(d.severity, "value") else str(d.severity)
            if sev == Severity.FATAL_INVARIANT.value:
                fatal_directives.append(d)
            else:
                advisory_directives.append(d)

        for d in fatal_directives:
            lines.append(f"### [CRITICAL INVARIANT] {d.title} (`{d.id}`)")
            if d.implements:
                lines.append(f"- Implements: {', '.join(d.implements)}")
            if d.body:
                lines.append(d.body.strip())
            lines.append("")

        if advisory_directives:
            lines.extend([
                "## Development Guidelines & Policies",
                "",
            ])
            for d in advisory_directives:
                lines.append(f"### {d.title} (`{d.id}`)")
                if d.body:
                    lines.append(d.body.strip())
                lines.append("")

        if skills:
            lines.extend([
                "## Workflows & Procedural Instructions",
                "",
            ])
            for s in skills:
                lines.append(f"### Workflow: {s.title} (`{s.id}`)")
                if s.triggers:
                    lines.append(f"- Trigger Keywords: {', '.join(s.triggers)}")
                if s.body:
                    lines.append(s.body.strip())
                lines.append("")

        if tools:
            lines.extend([
                "## Tool Usage Guidelines",
                "",
            ])
            for t in tools:
                lines.append(f"### Tool: {t.title} (`{t.id}`)")
                if t.body:
                    lines.append(t.body.strip())
                lines.append("")

        return [
            GeneratedArtifact(
                target=self.target_id,
                path=".windsurfrules",
                content="\n".join(lines),
                description="Global rules and workflow instructions for Windsurf Cascade",
            )
        ]

    def preview_node(self, node: HarnessNode, workspace: Workspace) -> GeneratedArtifact:
        sev = getattr(node, "severity", None)
        sev_tag = f"[{sev.value.upper()}] " if sev else ""
        lines = [
            f"### {sev_tag}{node.title} (`{node.id}`)",
            "",
            getattr(node, "body", "").strip(),
        ]
        return GeneratedArtifact(
            target=self.target_id,
            path=".windsurfrules",
            content="\n".join(lines),
            description="Windsurf rule preview",
        )

    def validate_compatibility(self, node: HarnessNode) -> List[CompatibilityDiagnostic]:
        diagnostics: List[CompatibilityDiagnostic] = []
        if isinstance(node, Skill):
            diagnostics.append(
                CompatibilityDiagnostic(
                    node_id=node.id,
                    target=self.target_id,
                    message="Windsurf Cascade does not support autonomous subagent routing; workflow flattened to workspace rule-block.",
                    severity="warning",
                    feature="subagents",
                    lossy=True,
                )
            )
        elif isinstance(node, ToolSpec):
            diagnostics.append(
                CompatibilityDiagnostic(
                    node_id=node.id,
                    target=self.target_id,
                    message="Windsurf Cascade does not auto-register custom shell tools; tool spec converted to prompt guideline.",
                    severity="warning",
                    feature="tools",
                    lossy=True,
                )
            )
        return diagnostics
