from __future__ import annotations

from typing import TYPE_CHECKING, List
from hrnx.models.schema import Directive, HarnessNode, Skill
from hrnx.transpiler.base import BaseAgentTranspiler, CompatibilityDiagnostic, GeneratedArtifact

if TYPE_CHECKING:
    from hrnx.workspace import Workspace


class AiderTranspiler(BaseAgentTranspiler):
    target_id = "aider"
    target_name = "Aider"
    target_file = "CONVENTIONS.md"
    supported_primitives = {"directives", "skills"}

    def compile(self, workspace: Workspace) -> List[GeneratedArtifact]:
        nodes = workspace.graph.all_nodes()
        directives = [n for n in nodes if isinstance(n, Directive)]
        skills = [n for n in nodes if isinstance(n, Skill)]

        lines = [
            "# Project Conventions & Coding Guidelines",
            "# AUTO-GENERATED BY HRNX - DO NOT EDIT MANUALLY",
            "",
            "## Architecture & Invariants",
            "",
        ]
        for d in directives:
            sev = d.severity.value if hasattr(d.severity, "value") else str(d.severity)
            lines.append(f"### {d.title} [{sev}]")
            if d.body:
                lines.append(d.body.strip())
            lines.append("")

        lines.extend([
            "## Workflows",
            "",
        ])
        for s in skills:
            lines.append(f"### {s.title}")
            if s.body:
                lines.append(s.body.strip())
            lines.append("")

        return [
            GeneratedArtifact(
                target=self.target_id,
                path="CONVENTIONS.md",
                content="\n".join(lines),
                description="Conventions file for Aider",
            )
        ]

    def preview_node(self, node: HarnessNode, workspace: Workspace) -> GeneratedArtifact:
        lines = [
            f"### {node.title} (`{node.id}`)",
            "",
            getattr(node, "body", "").strip(),
        ]
        return GeneratedArtifact(
            target=self.target_id,
            path="CONVENTIONS.md",
            content="\n".join(lines),
        )

    def validate_compatibility(self, node: HarnessNode) -> List[CompatibilityDiagnostic]:
        diagnostics: List[CompatibilityDiagnostic] = []
        if getattr(node, "type", None) == "tool" or node.__class__.__name__ == "ToolSpec":
            diagnostics.append(
                CompatibilityDiagnostic(
                    node_id=node.id,
                    target=self.target_id,
                    message="Aider does not execute custom tool specs; converted to prompt guideline.",
                    severity="warning",
                    feature="tools",
                    lossy=True,
                )
            )
        elif getattr(node, "type", None) == "skill" or node.__class__.__name__ == "Skill":
            diagnostics.append(
                CompatibilityDiagnostic(
                    node_id=node.id,
                    target=self.target_id,
                    message="Aider lacks multi-agent routing; workflow flattened to CONVENTIONS.md.",
                    severity="info",
                    feature="subagents",
                    lossy=True,
                )
            )
        elif isinstance(node, Directive):
            diagnostics.append(
                CompatibilityDiagnostic(
                    node_id=node.id,
                    target=self.target_id,
                    message="Directive compiled to CONVENTIONS.md invariant section.",
                    severity="info",
                    feature="directives",
                    lossy=False,
                )
            )
        return diagnostics
