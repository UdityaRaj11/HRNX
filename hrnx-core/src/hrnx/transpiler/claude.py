from __future__ import annotations

from typing import TYPE_CHECKING, List
from hrnx.models.schema import Directive, HarnessNode, Skill, ToolSpec
from hrnx.transpiler.base import BaseAgentTranspiler, CompatibilityDiagnostic, GeneratedArtifact

if TYPE_CHECKING:
    from hrnx.workspace import Workspace


class ClaudeTranspiler(BaseAgentTranspiler):
    target_id = "claude"
    target_name = "Anthropic Claude Code"
    target_file = "CLAUDE.md"
    supported_primitives = {"directives", "skills", "tools", "evals", "adrs", "subagents", "hooks"}

    def compile(self, workspace: Workspace) -> List[GeneratedArtifact]:
        nodes = workspace.graph.all_nodes()
        directives = [n for n in nodes if isinstance(n, Directive)]
        skills = [n for n in nodes if isinstance(n, Skill)]
        tools = [n for n in nodes if isinstance(n, ToolSpec)]

        lines = [
            "<!-- AUTO-GENERATED BY HRNX - DO NOT EDIT DIRECTLY -->",
            "<!-- Source: .hrnx/ canonical knowledge graph -->",
            "",
            "# Claude Code System Instructions",
            "",
            "<rules>",
            "  <architectural_invariants>",
        ]

        for d in directives:
            sev = d.severity.value if hasattr(d.severity, "value") else str(d.severity)
            lines.append(f'    <invariant id="{d.id}" severity="{sev}" title="{d.title}">')
            if d.body:
                for bline in d.body.strip().splitlines():
                    lines.append(f"      {bline}")
            lines.append("    </invariant>")

        lines.extend([
            "  </architectural_invariants>",
            "",
            "  <workflows>",
        ])

        for s in skills:
            lines.append(f'    <workflow id="{s.id}" title="{s.title}">')
            if s.triggers:
                lines.append(f"      <triggers>{', '.join(s.triggers)}</triggers>")
            if s.body:
                for bline in s.body.strip().splitlines():
                    lines.append(f"      {bline}")
            lines.append("    </workflow>")

        lines.extend([
            "  </workflows>",
            "",
            "  <tools>",
        ])

        for t in tools:
            lines.append(f'    <tool id="{t.id}" title="{t.title}" provider="{t.provider.value if hasattr(t.provider, "value") else t.provider}">')
            if t.body:
                for bline in t.body.strip().splitlines():
                    lines.append(f"      {bline}")
            lines.append("    </tool>")

        lines.extend([
            "  </tools>",
            "</rules>",
            "",
        ])

        content = "\n".join(lines)
        return [
            GeneratedArtifact(
                target=self.target_id,
                path="CLAUDE.md",
                content=content,
                description="Canonical instructions formatted for Anthropic Claude Code",
            )
        ]

    def preview_node(self, node: HarnessNode, workspace: Workspace) -> GeneratedArtifact:
        if isinstance(node, Directive):
            sev = node.severity.value if hasattr(node.severity, "value") else str(node.severity)
            lines = [
                f'<invariant id="{node.id}" severity="{sev}" title="{node.title}">',
            ]
            if node.body:
                for bline in node.body.strip().splitlines():
                    lines.append(f"  {bline}")
            lines.append("</invariant>")
            content = "\n".join(lines)
        elif isinstance(node, Skill):
            lines = [f'<workflow id="{node.id}" title="{node.title}">']
            if node.triggers:
                lines.append(f"  <triggers>{', '.join(node.triggers)}</triggers>")
            if node.body:
                for bline in node.body.strip().splitlines():
                    lines.append(f"  {bline}")
            lines.append("</workflow>")
            content = "\n".join(lines)
        elif isinstance(node, ToolSpec):
            lines = [f'<tool id="{node.id}" title="{node.title}">']
            if node.body:
                for bline in node.body.strip().splitlines():
                    lines.append(f"  {bline}")
            lines.append("</tool>")
            content = "\n".join(lines)
        else:
            content = f"# {node.title} ({node.id})\n\n{getattr(node, 'body', '')}"

        return GeneratedArtifact(
            target=self.target_id,
            path="CLAUDE.md",
            content=content,
            description="Preview snippet for Claude Code",
        )

    def validate_compatibility(self, node: HarnessNode) -> List[CompatibilityDiagnostic]:
        diagnostics: List[CompatibilityDiagnostic] = []
        if isinstance(node, Directive):
            diagnostics.append(
                CompatibilityDiagnostic(
                    node_id=node.id,
                    target=self.target_id,
                    message="Native XML <invariant> schema with strict severity enforcement.",
                    severity="info",
                    feature="directives",
                    lossy=False,
                )
            )
        elif isinstance(node, Skill):
            diagnostics.append(
                CompatibilityDiagnostic(
                    node_id=node.id,
                    target=self.target_id,
                    message="Native XML <workflow> with subagent orchestration.",
                    severity="info",
                    feature="subagents",
                    lossy=False,
                )
            )
        elif isinstance(node, ToolSpec):
            diagnostics.append(
                CompatibilityDiagnostic(
                    node_id=node.id,
                    target=self.target_id,
                    message="Native shell hook and tool specification.",
                    severity="info",
                    feature="tools",
                    lossy=False,
                )
            )
        return diagnostics
