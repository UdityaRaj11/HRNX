from __future__ import annotations

from typing import TYPE_CHECKING, List
from hrnx.models.schema import ContextSlice, Directive, HarnessNode
from hrnx.transpiler.base import BaseAgentTranspiler, CompatibilityDiagnostic, GeneratedArtifact

if TYPE_CHECKING:
    from hrnx.workspace import Workspace


class CursorTranspiler(BaseAgentTranspiler):
    target_id = "cursor"
    target_name = "Cursor"
    target_file = ".cursorrules"
    supported_primitives = {"directives", "context", "skills"}

    def compile(self, workspace: Workspace) -> List[GeneratedArtifact]:
        artifacts: List[GeneratedArtifact] = []
        nodes = workspace.graph.all_nodes()
        directives = [n for n in nodes if isinstance(n, Directive)]

        # Global .cursorrules
        global_lines = [
            "# Cursor Rules & Invariants",
            "# AUTO-GENERATED BY HRNX - DO NOT EDIT MANUALLY",
            "",
        ]
        for d in directives:
            sev = d.severity.value if hasattr(d.severity, "value") else str(d.severity)
            global_lines.append(f"## [{sev.upper()}] {d.title} ({d.id})")
            if d.body:
                global_lines.append(d.body.strip())
            global_lines.append("")

        artifacts.append(
            GeneratedArtifact(
                target=self.target_id,
                path=".cursorrules",
                content="\n".join(global_lines),
                description="Global rules for Cursor IDE",
            )
        )

        # Scoped .cursor/rules/*.mdc
        for d in directives:
            clean_name = d.id.replace("dir.", "").replace(".", "-")
            mdc_lines = [
                "---",
                f"description: {d.title}",
                "globs: *",
                "alwaysApply: true",
                "---",
                "",
                f"# {d.title}",
                "",
                f"**Invariant ID:** `{d.id}`",
                f"**Severity:** `{d.severity.value if hasattr(d.severity, 'value') else d.severity}`",
                "",
            ]
            if d.body:
                mdc_lines.append(d.body.strip())
            artifacts.append(
                GeneratedArtifact(
                    target=self.target_id,
                    path=f".cursor/rules/{clean_name}.mdc",
                    content="\n".join(mdc_lines),
                    description=f"Scoped rule for {clean_name}",
                )
            )

        return artifacts

    def preview_node(self, node: HarnessNode, workspace: Workspace) -> GeneratedArtifact:
        clean_name = node.id.replace("dir.", "").replace(".", "-")
        lines = [
            "---",
            f"description: {node.title}",
            "globs: *",
            "alwaysApply: true",
            "---",
            "",
            f"# {node.title}",
            "",
            getattr(node, "body", "").strip(),
        ]
        return GeneratedArtifact(
            target=self.target_id,
            path=f".cursor/rules/{clean_name}.mdc",
            content="\n".join(lines),
            description="Preview snippet for Cursor",
        )

    def validate_compatibility(self, node: HarnessNode) -> List[CompatibilityDiagnostic]:
        diagnostics: List[CompatibilityDiagnostic] = []
        if isinstance(node, ContextSlice):
            diagnostics.append(
                CompatibilityDiagnostic(
                    node_id=node.id,
                    target=self.target_id,
                    message="ContextSlice globs mapped directly to Cursor .cursor/rules/*.mdc file targets.",
                    severity="info",
                    feature="globs",
                    lossy=False,
                )
            )
        elif getattr(node, "type", None) == "tool" or node.__class__.__name__ == "ToolSpec":
            diagnostics.append(
                CompatibilityDiagnostic(
                    node_id=node.id,
                    target=self.target_id,
                    message="Cursor .cursorrules does not execute custom shell tools; tool specs omitted.",
                    severity="warning",
                    feature="tools",
                    lossy=True,
                )
            )
        elif getattr(node, "type", None) == "skill" or node.__class__.__name__ == "Skill":
            diagnostics.append(
                CompatibilityDiagnostic(
                    node_id=node.id,
                    target=self.target_id,
                    message="Cursor lacks autonomous multi-agent routing; skill flattened to markdown rule.",
                    severity="warning",
                    feature="subagents",
                    lossy=True,
                )
            )
        elif isinstance(node, Directive):
            diagnostics.append(
                CompatibilityDiagnostic(
                    node_id=node.id,
                    target=self.target_id,
                    message="Directive compiled to .cursorrules and scoped .cursor/rules/*.mdc rule.",
                    severity="info",
                    feature="directives",
                    lossy=False,
                )
            )
        return diagnostics
