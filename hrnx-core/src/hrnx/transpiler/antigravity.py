from __future__ import annotations

from typing import TYPE_CHECKING, List
from hrnx.models.schema import Directive, HarnessNode, Skill, ToolSpec
from hrnx.transpiler.base import BaseAgentTranspiler, CompatibilityDiagnostic, GeneratedArtifact

if TYPE_CHECKING:
    from hrnx.workspace import Workspace


class AntigravityTranspiler(BaseAgentTranspiler):
    target_id = "antigravity"
    target_name = "Google Antigravity"
    target_file = ".agent/rules.md"
    supported_primitives = {"directives", "skills", "tools", "evals", "adrs", "subagents", "mcp"}

    def compile(self, workspace: Workspace) -> List[GeneratedArtifact]:
        artifacts: List[GeneratedArtifact] = []
        nodes = workspace.graph.all_nodes()
        directives = [n for n in nodes if isinstance(n, Directive)]
        skills = [n for n in nodes if isinstance(n, Skill)]

        # 1. Main rules.md
        rules_lines = [
            "# Google Antigravity Rules & Invariants",
            "<!-- AUTO-GENERATED BY HRNX -->",
            "",
            "## Invariants & Policies",
            "",
        ]
        for d in directives:
            sev = d.severity.value if hasattr(d.severity, "value") else str(d.severity)
            rules_lines.append(f"### `{d.id}`: {d.title}")
            rules_lines.append(f"- **Severity:** `{sev}`")
            if d.implements:
                rules_lines.append(f"- **Implements:** {', '.join(d.implements)}")
            rules_lines.append("")
            if d.body:
                rules_lines.append(d.body.strip())
            rules_lines.append("")

        artifacts.append(
            GeneratedArtifact(
                target=self.target_id,
                path=".agent/rules.md",
                content="\n".join(rules_lines),
                description="Global directives for Antigravity",
            )
        )

        # 2. Skills as .agent/skills/<name>/SKILL.md
        for s in skills:
            clean_name = s.id.replace("skill.", "").replace(".", "-")
            skill_lines = [
                "---",
                f"name: {clean_name}",
                f"description: {s.title}",
            ]
            if s.triggers:
                skill_lines.append(f"triggers: [{', '.join(repr(t) for t in s.triggers)}]")
            skill_lines.extend([
                "---",
                "",
                f"# {s.title}",
                "",
            ])
            if s.body:
                skill_lines.append(s.body.strip())
            artifacts.append(
                GeneratedArtifact(
                    target=self.target_id,
                    path=f".agent/skills/{clean_name}/SKILL.md",
                    content="\n".join(skill_lines),
                    description=f"Skill workflow for {clean_name}",
                )
            )

        return artifacts

    def preview_node(self, node: HarnessNode, workspace: Workspace) -> GeneratedArtifact:
        if isinstance(node, Skill):
            clean_name = node.id.replace("skill.", "").replace(".", "-")
            lines = [
                "---",
                f"name: {clean_name}",
                f"description: {node.title}",
            ]
            if node.triggers:
                lines.append(f"triggers: [{', '.join(repr(t) for t in node.triggers)}]")
            lines.extend([
                "---",
                "",
                f"# {node.title}",
                "",
            ])
            if node.body:
                lines.append(node.body.strip())
            return GeneratedArtifact(
                target=self.target_id,
                path=f".agent/skills/{clean_name}/SKILL.md",
                content="\n".join(lines),
            )
        elif isinstance(node, Directive):
            sev = node.severity.value if hasattr(node.severity, "value") else str(node.severity)
            lines = [
                f"### `{node.id}`: {node.title}",
                f"- **Severity:** `{sev}`",
                "",
                node.body.strip() if node.body else "",
            ]
            return GeneratedArtifact(
                target=self.target_id,
                path=".agent/rules.md",
                content="\n".join(lines),
            )
        return GeneratedArtifact(
            target=self.target_id,
            path=".agent/rules.md",
            content=f"# {node.title} ({node.id})\n\n{getattr(node, 'body', '')}",
        )

    def validate_compatibility(self, node: HarnessNode) -> List[CompatibilityDiagnostic]:
        diagnostics: List[CompatibilityDiagnostic] = []
        if isinstance(node, Directive):
            diagnostics.append(
                CompatibilityDiagnostic(
                    node_id=node.id,
                    target=self.target_id,
                    message="Strict frontmatter & markdown policies in .agent/rules.md.",
                    severity="info",
                    feature="directives",
                    lossy=False,
                )
            )
        elif isinstance(node, Skill):
            clean_name = node.id.replace("skill.", "").replace(".", "-")
            diagnostics.append(
                CompatibilityDiagnostic(
                    node_id=node.id,
                    target=self.target_id,
                    message=f"Compiled to dedicated Antigravity skill (.agent/skills/{clean_name}/SKILL.md).",
                    severity="info",
                    feature="skills",
                    lossy=False,
                )
            )
        elif isinstance(node, ToolSpec):
            diagnostics.append(
                CompatibilityDiagnostic(
                    node_id=node.id,
                    target=self.target_id,
                    message="Native MCP server tool specification format.",
                    severity="info",
                    feature="mcp",
                    lossy=False,
                )
            )
        return diagnostics
