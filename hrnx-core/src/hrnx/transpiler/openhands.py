from __future__ import annotations

from typing import TYPE_CHECKING, List
from hrnx.models.schema import Directive, HarnessNode, Skill
from hrnx.transpiler.base import BaseAgentTranspiler, CompatibilityDiagnostic, GeneratedArtifact

if TYPE_CHECKING:
    from hrnx.workspace import Workspace


class OpenHandsTranspiler(BaseAgentTranspiler):
    target_id = "openhands"
    target_name = "OpenCode / OpenHands"
    target_file = ".openhands/instructions.md"
    supported_primitives = {"directives", "skills", "tools"}

    def compile(self, workspace: Workspace) -> List[GeneratedArtifact]:
        artifacts: List[GeneratedArtifact] = []
        nodes = workspace.graph.all_nodes()
        directives = [n for n in nodes if isinstance(n, Directive)]
        skills = [n for n in nodes if isinstance(n, Skill)]

        # Repo-level instructions
        lines = [
            "# OpenHands Agent Guidelines",
            "<!-- AUTO-GENERATED BY HRNX -->",
            "",
            "## Policies & Restrictions",
            "",
        ]
        for d in directives:
            sev = d.severity.value if hasattr(d.severity, "value") else str(d.severity)
            lines.append(f"### {d.title} (Severity: {sev})")
            if d.body:
                lines.append(d.body.strip())
            lines.append("")

        artifacts.append(
            GeneratedArtifact(
                target=self.target_id,
                path=".openhands/instructions.md",
                content="\n".join(lines),
                description="Repo-level instructions for OpenHands",
            )
        )

        # Microagents for each skill
        for s in skills:
            clean_name = s.id.replace("skill.", "").replace(".", "-")
            trig_str = f"Triggers: {', '.join(s.triggers)}" if s.triggers else ""
            micro_lines = [
                f"# Microagent: {s.title}",
                trig_str,
                "",
                s.body.strip() if s.body else "",
            ]
            artifacts.append(
                GeneratedArtifact(
                    target=self.target_id,
                    path=f".openhands/microagents/{clean_name}.md",
                    content="\n".join(micro_lines),
                    description=f"Triggered microagent for {s.title}",
                )
            )

        return artifacts

    def preview_node(self, node: HarnessNode, workspace: Workspace) -> GeneratedArtifact:
        if isinstance(node, Skill):
            clean_name = node.id.replace("skill.", "").replace(".", "-")
            lines = [
                f"# Microagent: {node.title}",
                f"Triggers: {', '.join(node.triggers)}" if node.triggers else "",
                "",
                node.body.strip() if node.body else "",
            ]
            return GeneratedArtifact(
                target=self.target_id,
                path=f".openhands/microagents/{clean_name}.md",
                content="\n".join(lines),
            )
        lines = [
            f"### {node.title} (`{node.id}`)",
            "",
            getattr(node, "body", "").strip(),
        ]
        return GeneratedArtifact(
            target=self.target_id,
            path=".openhands/instructions.md",
            content="\n".join(lines),
        )

    def validate_compatibility(self, node: HarnessNode) -> List[CompatibilityDiagnostic]:
        diagnostics: List[CompatibilityDiagnostic] = []
        if isinstance(node, Skill):
            if node.triggers:
                diagnostics.append(
                    CompatibilityDiagnostic(
                        node_id=node.id,
                        target=self.target_id,
                        message=f"Skill mapped to OpenHands microagent with triggers: {', '.join(node.triggers)}.",
                        severity="info",
                        feature="triggers",
                        lossy=False,
                    )
                )
            else:
                diagnostics.append(
                    CompatibilityDiagnostic(
                        node_id=node.id,
                        target=self.target_id,
                        message="Skill has no explicit trigger keywords; will not automatically activate in OpenHands.",
                        severity="warning",
                        feature="triggers",
                        lossy=True,
                    )
                )
        elif isinstance(node, Directive):
            diagnostics.append(
                CompatibilityDiagnostic(
                    node_id=node.id,
                    target=self.target_id,
                    message="Directive compiled to OpenHands repo-level instructions.",
                    severity="info",
                    feature="directives",
                    lossy=False,
                )
            )
        return diagnostics
